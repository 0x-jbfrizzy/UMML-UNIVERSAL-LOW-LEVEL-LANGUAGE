// =========================================================================
// SUPPORT MODULE: Simple PWM Generator
// =========================================================================
module pwm_generator #(
    parameter CLK_FREQ = 12_000_000,
    parameter PWM_FREQ = 50
) (
    input  logic clk,
    input  logic rst_n,
    input  logic [15:0] duty_cycle,
    output logic pwm_out
);
    localparam COUNTER_MAX = (CLK_FREQ / PWM_FREQ) - 1;
    logic [15:0] counter;

    always_ff @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            counter <= 0;
            pwm_out <= 0;
        end else begin
            if (counter >= COUNTER_MAX) begin
                counter <= 0;
            end else begin
                counter <= counter + 1;
            end
            
            // Map 16-bit duty cycle to PWM pulse
            // (Simplified mapping for proof of concept)
            pwm_out <= (counter < (duty_cycle >> 4)) ? 1'b1 : 1'b0;
        end
    end
endmodule
