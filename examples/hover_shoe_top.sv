module hover_shoe_top (
    // 1. System Clock & Reset (The Spine)
    input  logic clk_12mhz,       // Main FPGA clock
    input  logic rst_n,           // Active-low reset
    
    // 2. Physical Inputs (From Tether/Pad)
    input  logic pad_stick_press,
    input  logic pad_stick_backward,
    input  logic pad_nav_forward,
    input  logic pad_nav_backward,
    input  logic pad_nav_left,
    input  logic pad_nav_right,
    input  logic [15:0] pad_speed_selector, // From numeric keypad
    
    // 3. Physical Inputs (On-Shoe Sensors)
    input  logic shoe_emergency_btn_raw,    // Raw button press
    input  logic imu_scl,                   // I2C Clock
    inout  logic imu_sda,                   // I2C Data
    
    // 4. Physical Outputs (To Actuators)
    output logic thruster_left_pwm,         // To Left ESC
    output logic thruster_right_pwm,        // To Right ESC
    output logic mechanical_lock_engage,    // To Solenoid/Servo
    output logic status_led                 // System status indicator
);

    // =========================================================================
    // SIGNAL DEBOUNCING & CONDITIONING
    // =========================================================================
    // Raw mechanical buttons bounce. We debounce them to clean 1-bit signals.
    logic shoe_emergency_button;
    // (Instantiate a simple debounce module here in real implementation)
    assign shoe_emergency_button = shoe_emergency_btn_raw; 

    // =========================================================================
    // THE UMML BRAIN (Generated by compiler.awk)
    // =========================================================================
    // We instantiate the exact module generated from hover_shoe.umml
    umml_top umml_brain (
        .clk(clk_12mhz),
        .rst_n(rst_n),
        .spine_clk(clk_12mhz), // Spine uses main clock only during init
        .spine_en(1'b1),       // Enabled during boot, then gated by internal logic
        
        // Pad Inputs
        .speed_selector(pad_speed_selector),
        .right_stick_press(pad_stick_press),
        .right_stick_backward_hold(pad_stick_backward),
        .nav_forward(pad_nav_forward),
        .nav_backward(pad_nav_backward),
        .nav_left(pad_nav_left),
        .nav_right(pad_nav_right),
        
        // Shoe Inputs
        .shoe_emergency_button(shoe_emergency_button),
        
        // UMML Computed Outputs (Abstract Thrust Commands)
        .thruster_left(umml_thrust_left),
        .thruster_right(umml_thrust_right)
    );

    wire [15:0] umml_thrust_left;
    wire [15:0] umml_thrust_right;

    // =========================================================================
    // HARDWARE ABSTRACTION LAYER (HAL)
    // =========================================================================
    
    // 1. PWM GENERATOR FOR ESCs
    // Converts UMML's 16-bit abstract thrust command (0-65535) 
    // into a physical 50Hz PWM signal (1ms to 2ms pulse width).
    pwm_generator #(
        .CLK_FREQ(12_000_000),
        .PWM_FREQ(50)
    ) left_esc_driver (
        .clk(clk_12mhz),
        .rst_n(rst_n),
        .duty_cycle(umml_thrust_left), // 0 = 1ms (0%), 65535 = 2ms (100%)
        .pwm_out(thruster_left_pwm)
    );

    pwm_generator #(
        .CLK_FREQ(12_000_000),
        .PWM_FREQ(50)
    ) right_esc_driver (
        .clk(clk_12mhz),
        .rst_n(rst_n),
        .duty_cycle(umml_thrust_right),
        .pwm_out(thruster_right_pwm)
    );

    // 2. MECHANICAL LOCK ACTUATOR
    // Engages when UMML is in 'hover' state (state value 2)
    assign mechanical_lock_engage = (umml_brain.vertical_mode_state == 2);

    // 3. STATUS LED INDICATOR
    // Blinks or holds steady based on UMML state
    assign status_led = (umml_brain.vertical_mode_state == 3) ? 1'b1 : 1'b0; // Red on descent

